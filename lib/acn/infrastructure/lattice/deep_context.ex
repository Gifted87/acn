defmodule ACN.Infrastructure.Lattice.DeepContext do
  @moduledoc """
  The Six Pillars of Deep Context.
  Rigidly defined data structure that constitutes "Consciousness" for a node.
  """
  
  defmodule Rules do
    defstruct [
      master: [],      # System-wide safety (Immutable)
      ancestral: [],   # Union of Parent and Grandparent
      local: []        # Generated by current node's Legislator
    ]
  end

  defstruct [
    :blueprint,              # Pillar I: The technical narrative and architectural specification
    :file_manifest,          # Pillar I (Contract): Explicit list of relative file paths this node must produce
    :rules,                  # Pillar II: Master, Ancestral, and Local constraints
    :worksheets,             # Pillar III: Map of Parent, GP, GGP worksheet state
    :acms_results,           # Pillar IV: Semantic search results (Wisdom) - Full Node Bodies from CMS
    :task,                   # Pillar V: Atomic instruction
    :path,                   # Pillar VI: Absolute working directory
    :parent_node_id,         # Metadata: Parent Node ID for lattice functions
    :original_specification, # Pillar VII: Immutable root technical specification (full white paper)
    :specification_depth,    # Hierarchy depth for specification scoping (0=root, increments per generation)
    :specification_metadata  # Metadata about specification (version, timestamp, compliance requirements)
  ]

  @type t :: %__MODULE__{
    blueprint: String.t() | nil,
    file_manifest: list(String.t()) | nil,
    rules: %Rules{},
    worksheets: map(),
    acms_results: list(),
    task: String.t(),
    path: String.t(),
    parent_node_id: String.t() | nil,
    original_specification: String.t() | nil,
    specification_depth: non_neg_integer() | nil,
    specification_metadata: map() | nil
  }
end
